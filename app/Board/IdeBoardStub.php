<?php

declare(strict_types=1);

namespace App\Board;

use App\PhpbmException;
use App\Support\Files;
use PhpBaremetal\Spec\Sdk\Descriptor\Board;
use PhpBaremetal\Spec\Sdk\Sdk;

/**
 * Writes .phpbm/ide/board.php: the board's pin names (Baremetal\Board\Pin and, with the option
 * board-constants 'global', global constants) for the IDE. The firmware defines them at runtime.
 */
final class IdeBoardStub
{
    public const PATH = '.phpbm/ide/board.php';
    public const OPTION = 'board-constants';

    /** Whether the pins are global constants too: the project's option, else the SDK's default, else 'class'. @param array<string,mixed> $options */
    public static function global(array $options, ?Sdk $sdk = null): bool
    {
        $value = $options[self::OPTION] ?? $sdk?->descriptor->options[self::OPTION]->default ?? 'class';
        return $value === 'global' || (is_array($value) && in_array('global', $value, true));
    }

    public static function render(Board $board, bool $global): string
    {
        $class = '';
        $constants = '';
        foreach ($board->pins as $name => $gpio) {
            $class .= "        public const {$name} = {$gpio};\n";
            $constants .= "    const {$name} = {$gpio};\n";
        }
        $php = "<?php\n\n"
            . "// Generated by phpbm, do not edit: the pin names of board {$board->id}, for the IDE.\n"
            . "// phpbm rewrites this file at init, board and build.\n\n"
            . "namespace Baremetal\\Board {\n"
            . "    final class Pin\n    {\n{$class}    }\n"
            . "}\n";
        if ($global) {
            $php .= "\nnamespace {\n{$constants}}\n";
        }
        return $php;
    }

    /** Writes the file unless it already holds the same content; returns whether it wrote it. */
    public static function write(string $projectDir, Board $board, bool $global): bool
    {
        $path = rtrim($projectDir, '/\\') . '/' . self::PATH;
        $php = self::render($board, $global);
        if (is_file($path) && file_get_contents($path) === $php) {
            return false;
        }
        $dir = dirname($path);
        if (!is_dir($dir) && !@mkdir($dir, 0777, true) && !is_dir($dir)) {
            throw new PhpbmException("cannot create {$dir}");
        }
        $tmp = $path . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($tmp, $php) === false || !Files::rename($tmp, $path)) {
            @unlink($tmp);
            throw new PhpbmException("cannot write {$path}");
        }
        return true;
    }
}
