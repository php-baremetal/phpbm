<?php

declare(strict_types=1);

namespace App\Fonts;

use App\PhpbmException;

/** Writes the GFX-extended font header that ext-display reads (display_font_t, GFXglyph, display_font_range_t). */
final class FontHeaderWriter
{
    public const MAX_BITMAP = 0xFFFF;

    /** @param list<Glyph> $glyphs */
    public static function write(string $name, string $symbol, int $bpp, int $lineHeight, int $ascent, array $glyphs): string
    {
        usort($glyphs, fn (Glyph $a, Glyph $b) => $a->codepoint <=> $b->codepoint);
        foreach ($glyphs as $i => $glyph) {
            if ($i > 0 && $glyphs[$i - 1]->codepoint === $glyph->codepoint) {
                throw new PhpbmException(sprintf("font '%s': glyph U+%04X is given twice", $name, $glyph->codepoint));
            }
        }
        $total = array_sum(array_map(fn (Glyph $g) => self::glyphBytes($g, $bpp), $glyphs));
        if ($total > self::MAX_BITMAP) {
            throw self::tooLarge($name);
        }
        if ($lineHeight < 0 || $lineHeight > 255 || $ascent < 0 || $ascent > 255) {
            throw new PhpbmException("font '{$name}': line height {$lineHeight} or ascent {$ascent} is out of 0..255");
        }

        $bitmap = '';
        $entries = [];
        foreach ($glyphs as $glyph) {
            self::check($name, $glyph);
            $entries[] = sprintf(
                '    { %d, %d, %d, %d, %d, %d }, /* U+%04X */',
                strlen($bitmap), $glyph->width, $glyph->height, $glyph->xAdvance, $glyph->xOffset, $glyph->yOffset, $glyph->codepoint,
            );
            $bitmap .= self::pack($glyph, $bpp);
        }

        $ranges = [];
        $index = 0;
        foreach (CharSet::runs(array_map(fn (Glyph $g) => $g->codepoint, $glyphs)) as [$first, $last]) {
            $ranges[] = sprintf('    { 0x%02X, 0x%02X, %d },', $first, $last, $index);
            $index += $last - $first + 1;
        }

        $bytes = array_map(fn (int $b) => sprintf('0x%02X,', $b), array_values(unpack('C*', $bitmap === '' ? "\0" : $bitmap)));
        $lines = array_map(fn (array $chunk) => '    ' . implode(' ', $chunk), array_chunk($bytes, 12));

        return implode("\n", [
            sprintf('/* php-baremetal font %s: %d glyphs, %d bpp, generated by phpbm font:bake (baker v%d) */', $name, count($glyphs), $bpp, FontBaker::VERSION),
            "static const uint8_t {$symbol}_bitmap[] = {",
            ...$lines,
            '};',
            "static const GFXglyph {$symbol}_glyphs[] = {",
            ...$entries,
            '};',
            "static const display_font_range_t {$symbol}_ranges[] = {",
            ...$ranges,
            '};',
            sprintf(
                'const display_font_t %1$s = { %1$s_bitmap, %1$s_glyphs, %1$s_ranges, %2$d, %3$d, %4$d, %5$d };',
                $symbol, count($ranges), $bpp, $lineHeight, $ascent,
            ),
        ]) . "\n";
    }

    public static function glyphBytes(Glyph $glyph, int $bpp): int
    {
        return intdiv($glyph->width * $glyph->height * $bpp + 7, 8);
    }

    public static function tooLarge(string $name): PhpbmException
    {
        return new PhpbmException("font '{$name}' is larger than 64 KB: use fewer characters or a smaller size");
    }

    private static function check(string $name, Glyph $g): void
    {
        $cp = sprintf('U+%04X', $g->codepoint);
        if (max($g->width, $g->height, $g->xAdvance) > 255 || min($g->width, $g->height, $g->xAdvance) < 0) {
            throw new PhpbmException("font '{$name}': glyph {$cp} is too large (width {$g->width}, height {$g->height}, xAdvance {$g->xAdvance}; max 255)");
        }
        if (max($g->xOffset, $g->yOffset) > 127 || min($g->xOffset, $g->yOffset) < -128) {
            throw new PhpbmException("font '{$name}': glyph {$cp} is offset too far (xOffset {$g->xOffset}, yOffset {$g->yOffset}; range -128..127)");
        }
    }

    /** Rows top to bottom, MSB first, bpp bits per pixel, zero-padded to a byte at the end of the glyph. */
    private static function pack(Glyph $glyph, int $bpp): string
    {
        $bytes = '';
        $acc = 0;
        $bits = 0;
        foreach ($glyph->coverage as $coverage) {
            $acc = ($acc << $bpp) | Glyph::level($coverage, $bpp);
            $bits += $bpp;
            if ($bits === 8) {
                $bytes .= chr($acc);
                [$acc, $bits] = [0, 0];
            }
        }
        return $bits > 0 ? $bytes . chr($acc << (8 - $bits)) : $bytes;
    }
}
