<?php

declare(strict_types=1);

use App\Fonts\FontBaker;
use App\Fonts\Glyph;
use App\PhpbmException;
use Tests\Support\Fixtures;

beforeEach(function () {
    $this->fonts = dirname(__DIR__, 2) . '/fixtures/fonts';
    $this->mono = $this->fonts . '/DejaVuSansMono.ttf';
    $this->baker = new FontBaker();
});

function ascii(Glyph $glyph): string
{
    $rows = array_map(
        fn (array $row) => implode('', array_map(fn (int $c) => $c > 0 ? '#' : '.', $row)),
        array_chunk($glyph->coverage, max(1, $glyph->width)),
    );
    return implode("\n", $rows) . "\n";
}

it('bakes a TTF into a display_font_t header', function () {
    $baked = $this->baker->bake($this->mono, 'mono-16', 16, 1, 'Hi', null);

    expect($baked->header)->toContain("const display_font_t font_mono_16 = { font_mono_16_bitmap, font_mono_16_glyphs, font_mono_16_ranges, 2, 1, 19, 15 };")
        ->and($baked->header)->toStartWith('/* php-baremetal font mono-16: 2 glyphs, 1 bpp, generated by phpbm font:bake (baker v1) */')
        ->and($baked->header)->not->toContain('#include')
        ->and(array_map(fn (Glyph $g) => $g->codepoint, $baked->glyphs))->toBe([0x48, 0x69])
        ->and($baked->missing)->toBe([])
        ->and(FontBaker::VERSION)->toBe(1);
});

it('rasterizes H like the golden file', function () {
    $baked = $this->baker->bake($this->mono, 'mono-16', 16, 1, 'H', null);
    $h = $baked->glyphs[0];

    expect(ascii($h))->toBe(file_get_contents($this->fonts . '/H-16.txt'))
        ->and($h->xAdvance)->toBe(10)
        ->and($h->yOffset)->toBe(-$h->height);
});

it('gives the same bytes twice', function () {
    $bake = fn () => $this->baker->bake($this->mono, 'mono-12', 12, 2, null, '0x20-0x7E')->header;

    expect($bake())->toBe($bake());
});

it('bakes accented letters made of composite glyphs', function () {
    $baked = $this->baker->bake($this->mono, 'latin', 16, 1, null, '0xC0-0xFF');

    expect($baked->missing)->toBe([])
        ->and(count($baked->glyphs))->toBe(64);
});

it('reports the characters the source does not have', function () {
    $baked = $this->baker->bake($this->fonts . '/tiny.bdf', 'tiny', null, 1, 'I€', null);

    expect($baked->missing)->toBe([0x20AC])
        ->and(count($baked->glyphs))->toBe(1);
});

it('requires a size for a TTF source', function () {
    expect(fn () => $this->baker->bake($this->mono, 'mono', null, 1, 'Hi', null))
        ->toThrow(PhpbmException::class, "font 'mono': size is required for a TTF source");
});

it('rejects a bitmap larger than 64 KB', function () {
    expect(fn () => $this->baker->bake($this->mono, 'huge', 200, 1, null, '0x20-0xFF'))
        ->toThrow(PhpbmException::class, "font 'huge' is larger than 64 KB: use fewer characters or a smaller size");
});

it('names the font in source errors', function () {
    $dir = Fixtures::tempDir();
    file_put_contents("{$dir}/x.ttf", 'nope');

    expect(fn () => $this->baker->bake("{$dir}/missing.ttf", 'f', 16, 1, null, null))
        ->toThrow(PhpbmException::class, "font 'f': source '{$dir}/missing.ttf' not found")
        ->and(fn () => $this->baker->bake("{$dir}/x.ttf", 'f', 16, 1, null, null))
        ->toThrow(PhpbmException::class, "font 'f': '{$dir}/x.ttf' is not a TTF or BDF font");
});

it('validates the parameters', function (string $name, ?int $size, int $bpp, string $message) {
    expect(fn () => $this->baker->bake($this->mono, $name, $size, $bpp, null, null))->toThrow(PhpbmException::class, $message);
})->with([
    'name' => ['Mono_16', 16, 1, "font name 'Mono_16' is not valid: use lowercase letters, digits and '-'"],
    'bpp' => ['mono', 16, 3, "font 'mono': bpp must be 1, 2 or 4"],
    'size' => ['mono', 0, 1, "font 'mono': size must be a positive number of pixels"],
]);

it('rejects a source with none of the characters', function () {
    expect(fn () => $this->baker->bake($this->fonts . '/tiny.bdf', 'tiny', null, 1, '€', null))
        ->toThrow(PhpbmException::class, "font 'tiny': none of the characters is in the source");
});

it('rejects scaled and point-matched composites', function (int $set, int $clear, string $kind) {
    $file = Fixtures::tempDir() . '/patched.ttf';
    file_put_contents($file, patchFirstComponent($this->mono, 0xC9, $set, $clear));

    expect(fn () => $this->baker->bake($file, 'p', 16, 1, 'É', null))
        ->toThrow(PhpbmException::class, "font 'p': glyph U+00C9 uses a {$kind} composite, not supported");
})->with([
    'scaled' => [0x0008, 0, 'scaled'],
    'point-matched' => [0, 0x0002, 'point-matched'],
]);

/** Sets and clears flag bits of the first component of a composite glyph. */
function patchFirstComponent(string $font, int $codepoint, int $set, int $clear): string
{
    $data = (string) file_get_contents($font);
    $tables = [];
    for ($i = 0, $n = unpack('n', $data, 4)[1]; $i < $n; $i++) {
        $tables[substr($data, 12 + 16 * $i, 4)] = unpack('N', $data, 12 + 16 * $i + 8)[1];
    }
    $glyph = \App\Fonts\TrueTypeFont::fromFile($font)->glyphIndex($codepoint);
    $long = unpack('n', $data, $tables['head'] + 50)[1] === 1;
    $offset = $long ? unpack('N', $data, $tables['loca'] + 4 * $glyph)[1] : 2 * unpack('n', $data, $tables['loca'] + 2 * $glyph)[1];
    $at = $tables['glyf'] + $offset;
    expect(unpack('n', $data, $at)[1])->toBeGreaterThan(0x7FFF);
    $flags = (unpack('n', $data, $at + 10)[1] | $set) & ~$clear;
    return substr_replace($data, pack('n', $flags), $at + 10, 2);
}
