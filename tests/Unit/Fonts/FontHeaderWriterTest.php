<?php

declare(strict_types=1);

use App\Fonts\FontHeaderWriter;
use App\Fonts\Glyph;
use App\PhpbmException;

function letterI(): Glyph
{
    return new Glyph(0x49, 3, 5, 4, 0, -5, [
        255, 255, 255,
        0, 255, 0,
        0, 255, 0,
        0, 255, 0,
        255, 255, 255,
    ]);
}

it('writes a GFX-extended header', function () {
    $space = new Glyph(0x20, 0, 0, 4, 0, 0, []);
    $dash = new Glyph(0x2D, 2, 1, 4, 1, -2, [255, 128]);

    expect(FontHeaderWriter::write('tiny', 'font_tiny', 1, 6, 5, [letterI(), $dash, $space]))->toBe(<<<'C'
/* php-baremetal font tiny: 3 glyphs, 1 bpp, generated by phpbm font:bake (baker v1) */
static const uint8_t font_tiny_bitmap[] = {
    0xC0, 0xE9, 0x2E,
};
static const GFXglyph font_tiny_glyphs[] = {
    { 0, 0, 0, 4, 0, 0 }, /* U+0020 */
    { 0, 2, 1, 4, 1, -2 }, /* U+002D */
    { 1, 3, 5, 4, 0, -5 }, /* U+0049 */
};
static const display_font_range_t font_tiny_ranges[] = {
    { 0x20, 0x20, 0 },
    { 0x2D, 0x2D, 1 },
    { 0x49, 0x49, 2 },
};
const display_font_t font_tiny = { font_tiny_bitmap, font_tiny_glyphs, font_tiny_ranges, 3, 1, 6, 5 };

C);
});

it('quantizes coverage to the bpp, rounding to nearest', function () {
    $glyph = new Glyph(0x41, 4, 1, 5, 0, -1, [0, 85, 170, 255]);

    expect(FontHeaderWriter::write('q', 'font_q', 2, 2, 1, [$glyph]))->toContain("    0x1B,\n")
        ->and(FontHeaderWriter::write('q', 'font_q', 4, 2, 1, [$glyph]))->toContain("    0x05, 0xAF,\n");
});

it('groups contiguous codepoints into ranges', function () {
    $glyphs = array_map(fn (int $cp) => new Glyph($cp, 0, 0, 4, 0, 0, []), [0x41, 0x42, 0x43, 0x45]);

    expect(FontHeaderWriter::write('r', 'font_r', 1, 2, 1, $glyphs))->toContain("    { 0x41, 0x43, 0 },\n    { 0x45, 0x45, 3 },\n")
        ->and(FontHeaderWriter::write('r', 'font_r', 1, 2, 1, $glyphs))->toContain("    0x00,\n");
});

it('rejects a font larger than 64 KB', function () {
    $big = new Glyph(0x41, 255, 255, 255, 0, -100, array_fill(0, 255 * 255, 255));
    $glyphs = array_map(fn (int $cp) => new Glyph($cp, 255, 255, 255, 0, -100, $big->coverage), range(0x41, 0x50));

    expect(fn () => FontHeaderWriter::write('big', 'font_big', 1, 20, 10, $glyphs))
        ->toThrow(PhpbmException::class, "font 'big' is larger than 64 KB: use fewer characters or a smaller size");
});

it('rejects values that do not fit the GFX fields', function (array $g, int $lineHeight, int $ascent, string $message) {
    $glyph = new Glyph(0x41, $g[0], $g[1], $g[2], $g[3], $g[4], array_fill(0, $g[0] * $g[1], 255));
    expect(fn () => FontHeaderWriter::write('x', 'font_x', 1, $lineHeight, $ascent, [$glyph]))->toThrow(PhpbmException::class, $message);
})->with([
    'width' => [[256, 1, 4, 0, -1], 2, 1, "font 'x': glyph U+0041 is too large (width 256, height 1, xAdvance 4; max 255)"],
    'xAdvance' => [[0, 0, 300, 0, 0], 2, 1, "font 'x': glyph U+0041 is too large (width 0, height 0, xAdvance 300; max 255)"],
    'yOffset' => [[1, 1, 4, 0, -129], 2, 1, "font 'x': glyph U+0041 is offset too far (xOffset 0, yOffset -129; range -128..127)"],
    'line height' => [[1, 1, 4, 0, -1], 256, 1, "font 'x': line height 256 or ascent 1 is out of 0..255"],
    'ascent' => [[1, 1, 4, 0, -1], 2, 300, "font 'x': line height 2 or ascent 300 is out of 0..255"],
    'negative ascent' => [[1, 1, 4, 0, -1], 2, -1, "font 'x': line height 2 or ascent -1 is out of 0..255"],
]);

it('rejects the same codepoint twice', function () {
    expect(fn () => FontHeaderWriter::write('dup', 'font_dup', 1, 6, 5, [letterI(), letterI()]))
        ->toThrow(PhpbmException::class, "font 'dup': glyph U+0049 is given twice");
});
